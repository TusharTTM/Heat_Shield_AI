export const dictionaries: Record<LanguageCode, Record<MessageKey, string>> = { en, hi, mr, bn, ta, te }

export const languageOptions: Array<{ value: LanguageCode; label: string }> = [
  { value: 'en', label: 'English' },
  { value: 'hi', label: 'हिन्दी (Hindi)' },
  { value: 'mr', label: 'मराठी (Marathi)' },
  { value: 'bn', label: 'বাংলা (Bengali)' },
  { value: 'ta', label: 'தமிழ் (Tamil)' },
  { value: 'te', label: 'తెలుగు (Telugu)' },
]

export function translate(language: LanguageCode, key: MessageKey, params?: Record<string, string | number>): string {
  const template = dictionaries[language]?.[key] ?? en[key]
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
}

export type Translate = (key: MessageKey, params?: Record<string, string | number>) => string

export function useT(): Translate {
  const { settings } = useSettings()
  return useMemo(
    () => (key, params) => translate(settings.display.language, key, params),
    [settings.display.language],
  )
}
